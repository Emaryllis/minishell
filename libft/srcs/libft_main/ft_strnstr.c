#include "libft.h"

char	*ft_strnstr(const char *big, const char *little, size_t len)
{
	size_t	lil_len;
	size_t	i;
	size_t	j;

	if (little[0] == '\0')
		return ((char *)big);
	lil_len = ft_strlen(little);
	i = 0;
	while (big[i] != '\0' && i < len)
	{
		j = 0;
		if (big[i] == little[j])
		{
			while (big[i + j] == little [j] && i + j < len)
				j++;
			if (j == lil_len)
				return (&((char *)big)[i]);
		}
		i++;
	}
	return (NULL);
}
